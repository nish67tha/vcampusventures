document.addEventListener('DOMContentLoaded', function () {
    const links = document.querySelectorAll('#navmenu .page-nav-link');
    if (!links.length) return;

    const path = window.location.pathname.replace(/\/+$/, '').toLowerCase();
    const base = new URL('<?= base_url('/') ?>', window.location.origin)
        .pathname.replace(/\/+$/, '').toLowerCase();

    let page = 'home';

    if (path !== base && path !== base + '/index.php') {
        page = path.replace(base, '').split('/').filter(Boolean)[0] || 'home';
    }

    // All academic/domain pages keep Domain highlighted.
    if (page === 'academics') {
        page = 'domain';
    }

    links.forEach(function (link) {
        link.classList.toggle('page-active', link.dataset.page === page);
    });
});
</script>

<script>
function showStudyCountry(event, clickedCountry, panelId) {

    if (event) {
        event.preventDefault();
        event.stopPropagation();
    }

    const menu = document.querySelector('.study-abroad-menu');

    if (!menu) {
        return false;
    }

    /* Remove active from all country buttons */

    const countries = menu.querySelectorAll(
        '.study-country-item'
    );

    countries.forEach(function(country) {

        country.classList.remove('active');

    });


    /* Hide ALL country panels */

    const panels = menu.querySelectorAll(
        '.study-country-panel'
    );

    panels.forEach(function(panel) {

        panel.classList.remove('active');

        panel.style.setProperty(
            'display',
            'none',
            'important'
        );

    });


    /* Make clicked country active */

    clickedCountry.classList.add('active');


    /* Show ONLY selected country's panel */

    const selectedPanel = document.getElementById(panelId);

    if (selectedPanel) {

        selectedPanel.classList.add('active');

        selectedPanel.style.setProperty(
            'display',
            'block',
            'important'
        );

    }

    return false;
}


