<script>

document.addEventListener("DOMContentLoaded", function () {

    const videoCards =
        document.querySelectorAll(".vc-video-card");

    const featuredVideo =
        document.getElementById("featuredVideo");

    const featuredPlay =
        document.getElementById("featuredPlay");

    const featuredName =
        document.getElementById("featuredName");

    const featuredRole =
        document.getElementById("featuredRole");

    const featuredDescription =
        document.getElementById("featuredDescription");

    const carousel =
        document.getElementById("videoCarousel");

    const prevBtn =
        document.getElementById("prevBtn");

    const nextBtn =
        document.getElementById("nextBtn");


    /* =========================================
       LOAD SELECTED VIDEO INTO SAME BIG PLAYER
    ========================================= */

    function loadFeatured(card, autoplay = false) {

        if (!card) return;

        const video = card.dataset.video;
        const poster = card.dataset.poster;
        const name = card.dataset.name;
        const role = card.dataset.role;
        const description = card.dataset.description;


        /* Stop current video */

        featuredVideo.pause();


        /* Change video */

        featuredVideo.src = video;


        /* Change poster */

        if (poster) {
            featuredVideo.poster = poster;
        }


        /* Reload selected video */

        featuredVideo.load();


        /* Update text */

        featuredName.textContent = name;
        featuredRole.textContent = role;
        featuredDescription.textContent = description;


        /* Active card */

        videoCards.forEach(function (item) {

            item.classList.remove("active");

        });

        card.classList.add("active");


        /* Play selected video */

        if (autoplay) {

            featuredVideo.play()
                .then(function () {

                    featuredPlay.innerHTML = "❚❚";

                })
                .catch(function () {

                    featuredPlay.innerHTML = "▶";

                });

        }

    }


    /* =========================================
       THUMBNAIL CLICK
    ========================================= */

    videoCards.forEach(function (card) {

        card.addEventListener("click", function () {

            loadFeatured(card, true);

        });

    });


    /* =========================================
       BIG VIDEO PLAY / PAUSE
    ========================================= */

    featuredPlay.addEventListener("click", function () {

        if (featuredVideo.paused) {

            featuredVideo.play();

        } else {

            featuredVideo.pause();

        }

    });


    /* =========================================
       PLAY EVENT
    ========================================= */

    featuredVideo.addEventListener("play", function () {

        featuredPlay.innerHTML = "❚❚";

    });


    /* =========================================
       PAUSE EVENT
    ========================================= */

    featuredVideo.addEventListener("pause", function () {

        featuredPlay.innerHTML = "▶";

    });


    /* =========================================
       PREVIOUS ARROW
    ========================================= */

    prevBtn.addEventListener("click", function () {

        carousel.scrollBy({

            left: -380,
            behavior: "smooth"

        });

    });


    /* =========================================
       NEXT ARROW
    ========================================= */

    nextBtn.addEventListener("click", function () {

        carousel.scrollBy({

            left: 380,
            behavior: "smooth"

        });

    });


    /* =========================================
       INITIAL VIDEO
    ========================================= */

    if (videoCards.length > 0) {

        loadFeatured(videoCards[0], false);

    }



});

</script>